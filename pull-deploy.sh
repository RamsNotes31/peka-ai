#!/bin/bash
# pull-deploy.sh — tarik update terbaru peka-ai dari GitHub, rebuild bila ada perubahan.
# Dijalankan oleh cron tiap 30 menit. Aman dijalankan manual juga.
set -u
cd /home/hatch/workspace/peka-ai || exit 1

git fetch origin -q 2>&1 | head -3
LOCAL=$(git rev-parse HEAD)
REMOTE=$(git rev-parse '@{u}' 2>/dev/null || echo "$LOCAL")

if [ "$LOCAL" = "$REMOTE" ]; then
  echo "no changes"
  exit 0
fi

echo "updating $LOCAL -> $REMOTE"

# npm install leaves npm's own lockfile-format artifact ("peer": true lines
# removed) as a local modification. It is a pure build artifact — discard it
# before pulling so it can never block a future fast-forward. Only do this
# when package-lock.json is the SOLE tracked modification (untracked files
# can't block a fast-forward and are left alone); anything else is left for
# the error path (cron reports it, no partial deploy).
LOCK_ONLY=$(git status --porcelain | grep -v '^??' | grep -v '^ M package-lock.json$' || true)
if [ -n "$(git status --porcelain package-lock.json)" ] && [ -z "$LOCK_ONLY" ]; then
  echo "discarding npm lockfile artifact (will be regenerated by npm install)"
  git checkout -- package-lock.json
fi

git pull --ff-only 2>&1 | tail -2 || exit 1

# package.json berubah -> install ulang dependensi
if git diff --name-only "$LOCAL" "$REMOTE" | grep -q "^package-lock.json$"; then
  echo "deps changed, npm install..."
  npm install --no-audit --no-fund 2>&1 | tail -1
fi

npm run build 2>&1 | grep -E "error|✓ built" | head -3 || exit 1
echo "deployed $(git rev-parse --short HEAD) — live tanpa restart (static)"
